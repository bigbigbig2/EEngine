import { spawnSync } from "node:child_process";
import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = fileURLToPath(new URL("../../", import.meta.url));
const basis = resolve(process.env.BASIS_SOURCE ?? join(root, ".local/texture-design-basis"));
const revision = "99f52d63aa6799cbdaecfe977111dc5ec3b31d47";
const emcc = join(process.env.EMSDK ?? "D:/Devtool/emsdk", "upstream/emscripten/emcc.exe");
const out = join(root, "OEngine/src/assets/codec/vendor/tiled-zstd");
const glue = join(root, "OEngine/tools/texture-codec/TiledZstd.c");
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
function run(command, args, cwd = root) {
  const result = spawnSync(command, args, { cwd, encoding: "utf8", windowsHide: true });
  if (result.status !== 0) throw new Error(result.error?.message ?? result.stderr);
  return result.stdout;
}
if (
  run("git", ["rev-parse", "HEAD"], basis).trim() !== revision ||
  run("git", ["diff", "HEAD", "--name-only"], basis).trim()
) {
  throw new Error("Tiled Zstd requires the clean pinned Basis source");
}
await mkdir(out, { recursive: true });
run(emcc, [
  glue,
  join(basis, "zstd/zstddeclib.c"),
  `-I${join(basis, "zstd")}`,
  "-O3",
  "-DNDEBUG",
  "-DZSTD_LEGACY_SUPPORT=0",
  "-DZSTD_DISABLE_ASM=1",
  "-sMODULARIZE=1",
  "-sEXPORT_ES6=1",
  "-sEXPORT_NAME=createTiledZstdModule",
  "-sENVIRONMENT=web,worker,node",
  "-sFILESYSTEM=0",
  "-sALLOW_MEMORY_GROWTH=0",
  "-sINITIAL_MEMORY=4194304",
  "-sSTACK_SIZE=262144",
  "-sEXPORTED_FUNCTIONS=['_tiled_init','_tiled_input','_tiled_output','_tiled_decode']",
  "-sEXPORTED_RUNTIME_METHODS=['HEAPU8']",
  "-o",
  join(out, "tiled_zstd.js"),
]);
await copyFile(join(basis, "zstd/LICENSE"), join(out, "LICENSE"));
const hashes = {};
const sizes = {};
for (const name of ["tiled_zstd.js", "tiled_zstd.wasm"]) {
  const bytes = await readFile(join(out, name));
  hashes[name] = hash(bytes);
  sizes[name] = bytes.byteLength;
}
const sourceHashes = {};
for (const name of ["zstddeclib.c", "zstd.h", "zstd_errors.h", "LICENSE"]) {
  sourceHashes[name] = hash(await readFile(join(basis, "zstd", name)));
}
await writeFile(
  join(out, "source.json"),
  JSON.stringify(
    {
      revision,
      version: "1.5.7",
      license: "BSD",
      sourceHashes,
      glueHash: hash(await readFile(glue)),
      compiler: run(emcc, ["--version"]).split("\n")[0].trim(),
      recipe: "OEngine/tools/build-tiled-texture-codec.mjs",
      memoryBytes: 4194304,
      hashes,
      sizes,
    },
    null,
    2,
  ) + "\n",
);
await writeFile(
  join(out, "identity.ts"),
  "// Generated by build-tiled-texture-codec.mjs.\n" +
    `export const TILED_ZSTD_WASM_HASH = "${hashes["tiled_zstd.wasm"]}";\n` +
    `export const TILED_ZSTD_WASM_BYTES = ${sizes["tiled_zstd.wasm"]};\n`,
);
