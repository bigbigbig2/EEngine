/** Shared CPU/WGSL directional projection layout. Mips are semantic, not planes. */
export const VSM_MAX_CLIP_LEVELS = 16;
export const VSM_DIMENSIONS_WORD = 16 + VSM_MAX_CLIP_LEVELS * 4;
export const VSM_CONTROL_WORD = VSM_DIMENSIONS_WORD + 4;
export const VSM_PARAMETERS_WORD = VSM_CONTROL_WORD + 4;
export const VSM_DEPTH_RANGE_BYTE_OFFSET = (VSM_PARAMETERS_WORD + 4) * 4;
export const VSM_IDENTITY_BYTE_OFFSET = VSM_DEPTH_RANGE_BYTE_OFFSET + 16;
export const VSM_SELECTOR_WORD = VSM_IDENTITY_BYTE_OFFSET / 4 + 4;
export const VSM_FOOTPRINT_WORD = VSM_SELECTOR_WORD + 4;
export const VSM_PROJECTION_CONSTANT_BYTES = (VSM_FOOTPRINT_WORD + 4) * 4;
export const VSM_RESIDENCY_CONSTANT_BYTES = 48 + VSM_MAX_CLIP_LEVELS * 16;
export const VSM_SHADOW_DOMAIN_HEADER_BYTES = 512;
export const VSM_SHADOW_DOMAIN_CONSTANT_BYTES = (VSM_DIMENSIONS_WORD + 4) * 4;
export const VSM_RECEIVER_DESCRIPTOR_REFERENCES = VSM_MAX_CLIP_LEVELS * 2;
