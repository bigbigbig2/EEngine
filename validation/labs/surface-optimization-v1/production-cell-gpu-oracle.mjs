import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {resolve} from 'node:path';
import {mkdir,writeFile} from 'node:fs/promises';
if(!process.argv[2])throw new Error('Pass external runtime directory');
const {create,globals}=createRequire(resolve(process.argv[2],'package.json'))('webgpu');Object.assign(globalThis,globals);
const {runProductionCellOracle}=await import('./production-cell-fixture.mjs');
const gpu=create([process.argv[3]??'backend=d3d12',...process.argv.slice(4)]);
await mkdir('.local/validation/surface-optimization-v1',{recursive:true});
const report=await runProductionCellOracle(gpu,assert,console.log,code=>writeFile('.local/validation/surface-optimization-v1/production-cell.wgsl',code));
await writeFile('.local/validation/surface-optimization-v1/production-cell-gpu-oracle.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report));assert.equal(report.passed,true,report.failure);
